/**
 * @file packet.h
 * @brief Wire format of an encrypted chat packet (server copy).
 *
 * Must match client/include/packet.h byte for byte. See that file for the
 * full description of the layout:
 *
 * @code
 *   +----------------+--------------------+------------------------------+
 *   | length (4 B)   | nonce (12 B)       | ciphertext (length bytes)    |
 *   +----------------+--------------------+------------------------------+
 * @endcode
 *
 * This header relies on <stdint.h> and <sodium.h> being included first.
 */
#ifndef PACKET_H
#define PACKET_H

/** Largest message (in bytes) accepted from or sent to a client. */
#define MAX_PLAINTEXT_LEN 1024

/** Largest ciphertext that fits in a packet: plaintext plus the AEAD tag. */
#define MAX_CIPHERTEXT_SIZE (MAX_PLAINTEXT_LEN + crypto_aead_chacha20poly1305_ietf_ABYTES)

/**
 * @brief In-memory representation of one encrypted packet.
 *
 * `length` is kept in host byte order; send_packet()/recv_packet() convert
 * it on the wire.
 */
struct packet_in
{
	/** Number of valid bytes in @ref ciphertext (host byte order). */
	uint32_t length;
	/** Random per-packet nonce, generated by packet_encrypt(). */
	uint8_t nonce[crypto_aead_chacha20poly1305_ietf_NPUBBYTES];
	/** ChaCha20-Poly1305 ciphertext followed by the 16-byte auth tag. */
	uint8_t ciphertext[MAX_CIPHERTEXT_SIZE];
};


#endif
