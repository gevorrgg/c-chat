/**
 * @file packet.h
 * @brief Wire format of an encrypted chat packet.
 *
 * Every chat message travels over TCP as a @ref packet_in. The packet is
 * serialised field by field by send_packet() and parsed by recv_packet()
 * (see network.h). The plaintext never leaves the process unencrypted:
 * packet_encrypt() fills a packet from a message, packet_decrypt() does the
 * reverse (see crypto.h).
 *
 * On the wire a packet looks like this (all fields big-endian / raw bytes):
 *
 * @code
 *   +----------------+--------------------+------------------------------+
 *   | length (4 B)   | nonce (12 B)       | ciphertext (length bytes)    |
 *   +----------------+--------------------+------------------------------+
 * @endcode
 *
 * The ciphertext already contains the 16-byte Poly1305 authentication tag,
 * so `length` is always `plaintext_len + crypto_aead_chacha20poly1305_ietf_ABYTES`.
 */
#ifndef PACKET_H
#define PACKET_H

#include <stdint.h>
#include <sodium.h>

/** Largest message (in bytes) a client may type or receive. */
#define MAX_PLAINTEXT_LEN 1024

/** Largest ciphertext that fits in a packet: plaintext plus the AEAD tag. */
#define MAX_CIPHERTEXT_SIZE (MAX_PLAINTEXT_LEN + crypto_aead_chacha20poly1305_ietf_ABYTES)

/**
 * @brief In-memory representation of one encrypted packet.
 *
 * The struct is used both for incoming and outgoing packets. `length` is
 * stored in host byte order; send_packet()/recv_packet() convert it to and
 * from network byte order.
 */
struct packet_in
{
	/** Number of valid bytes in @ref ciphertext (host byte order). */
	uint32_t length;
	/** Random per-packet nonce, generated by packet_encrypt(). */
	uint8_t nonce[crypto_aead_chacha20poly1305_ietf_NPUBBYTES];
	/** ChaCha20-Poly1305 ciphertext followed by the 16-byte auth tag. */
	uint8_t ciphertext[MAX_CIPHERTEXT_SIZE];
};


#endif
